let lang = 'en';
const listeners = new Set();

export function getLang() { return lang; }

export function t(key, vars = {}) {
  let text = dict[lang]?.[key] ?? dict.ko[key] ?? key;
  for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

export function tServer(text) {
  const key = serverText[text];
  return key ? t(key) : text;
}

function paint() {
  document.documentElement.lang = lang === 'en' ? 'en' : 'ko';
  document.documentElement.dataset.lang = lang;
  const titleKey = document.documentElement.dataset.i18nTitle;
  if (titleKey) document.title = t(titleKey);
  document.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
  document.querySelectorAll('[data-i18n-aria]').forEach(node => { node.setAttribute('aria-label', t(node.dataset.i18nAria)); });
  document.querySelectorAll('[data-set-lang]').forEach(node => {
    node.setAttribute('aria-pressed', String(node.dataset.setLang === lang));
  });
}

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'ko';
  try { localStorage.setItem('safeteyed-lang', lang); } catch { /* private mode */ }
  paint();
  for (const listener of listeners) listener(lang);
}

export function onLang(listener) { listeners.add(listener); }

/** Page-specific dictionaries extend the shared one; existing keys are never overwritten. */
export function addMessages(table) {
  for (const code of ['ko', 'en']) {
    for (const [key, value] of Object.entries(table[code] ?? {})) if (!Object.hasOwn(dict[code], key)) dict[code][key] = value;
  }
  if (document.readyState !== 'loading') paint();
}

function mount() {
  const saved = (() => { try { return localStorage.getItem('safeteyed-lang'); } catch { return null; } })();
  const query = new URLSearchParams(location.search).get('lang');
  lang = query === 'en' || query === 'ko' ? query : saved === 'ko' ? 'ko' : 'en';
  document.querySelectorAll('[data-set-lang]').forEach(node => {
    node.addEventListener('click', () => setLang(node.dataset.setLang));
  });
  paint();
}

if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', mount);
else mount();
